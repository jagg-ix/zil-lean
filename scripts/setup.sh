#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"

profile="lean"
install_tools=false
build=true
run_tests=false
test_profile=""
offline=false
report="$ZIL_ROOT/.zil/setup-report.tsv"

usage() {
  cat <<'EOF'
Usage: bash scripts/setup.sh [options]

Options:
  --profile lean
  --install-tools       Install a missing Elan in user space
  --no-build            Diagnose and prepare dependencies without building
  --test                Run the profile's default tests after setup
  --test-profile NAME   Run a specific scripts/test.sh profile
  --offline             Do not download or install missing tools
  --report FILE         Setup report path (default: .zil/setup-report.tsv)

The script never installs Git, Docker, Make, or OS packages and never uses
sudo. Install those prerequisites explicitly when the doctor reports them missing.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --profile)
      [[ $# -ge 2 ]] || zil_die '--profile requires a value'
      profile="$2"
      shift 2
      ;;
    --install-tools)
      install_tools=true
      shift
      ;;
    --no-build)
      build=false
      shift
      ;;
    --test)
      run_tests=true
      shift
      ;;
    --test-profile)
      [[ $# -ge 2 ]] || zil_die '--test-profile requires a value'
      run_tests=true
      test_profile="$2"
      shift 2
      ;;
    --offline)
      offline=true
      shift
      ;;
    --report)
      [[ $# -ge 2 ]] || zil_die '--report requires a value'
      report="$2"
      shift 2
      ;;
    --help|-h)
      usage
      exit 0
      ;;
    *)
      zil_die "unknown setup option: $1"
      ;;
  esac
done

case "$profile" in
  lean) ;;
  *) zil_die "unknown setup profile: $profile" ;;
esac

report="$(zil_abs_path "$report")"
mkdir -p "$ZIL_ROOT/.zil"
export PATH="$HOME/.elan/bin:$PATH"

require_installer_command() {
  local name="$1"
  zil_command_exists "$name" || zil_die "$name is required to install missing tools"
}

install_elan() {
  if zil_command_exists elan; then
    return
  fi
  [[ "$install_tools" == true ]] || return
  [[ "$offline" != true ]] || zil_die 'Elan is missing and --offline forbids installation'
  require_installer_command curl
  zil_log 'installing Elan without a default global toolchain'
  curl --fail --location --silent --show-error \
    https://elan.lean-lang.org/elan-init.sh | \
    sh -s -- -y --default-toolchain none
  export PATH="$HOME/.elan/bin:$PATH"
}

install_elan

bash "$SCRIPT_DIR/doctor.sh" --profile "$profile" \
  --report "$ZIL_ROOT/.zil/doctor-$profile.tsv"

cd "$ZIL_ROOT"

if [[ "$build" == true ]]; then
  zil_log 'building the Lean package'
  lake build
fi

cat > "$ZIL_ROOT/.zil/setup.env" <<EOF
# Generated by scripts/setup.sh. Source this file in a compatible shell.
export ZIL_HOME="$ZIL_ROOT"
export PATH="$HOME/.elan/bin:\$PATH"
EOF

zil_mkdir_parent "$report"
{
  printf 'ZIL-SETUP-REPORT/1\n'
  printf 'profile\t%s\n' "$profile"
  printf 'root\t%s\n' "$(zil_tsv_escape "$ZIL_ROOT")"
  printf 'os\t%s\n' "$(zil_os)"
  printf 'arch\t%s\n' "$(zil_arch)"
  printf 'build\t%s\n' "$build"
  printf 'offline\t%s\n' "$offline"
  if zil_command_exists elan; then printf 'elan\t%s\n' "$(zil_tsv_escape "$(zil_first_line elan --version)")"; fi
  if zil_command_exists lean; then printf 'lean\t%s\n' "$(zil_tsv_escape "$(zil_first_line lean --version)")"; fi
  if zil_command_exists lake; then printf 'lake\t%s\n' "$(zil_tsv_escape "$(zil_first_line lake --version)")"; fi
  printf 'result\tpass\n'
} > "$report"

zil_log "setup report: $report"
zil_log "environment file: $ZIL_ROOT/.zil/setup.env"

if [[ "$run_tests" == true ]]; then
  [[ -n "$test_profile" ]] || test_profile=lean
  zil_log "running test profile: $test_profile"
  bash "$SCRIPT_DIR/test.sh" --profile "$test_profile"
fi

zil_log "setup complete for profile '$profile'"
